-- شريحة سعر واحدة لكل كمية، حتى حين لا يُحدَّد متغيّر.
--
-- سعرٌ للمنتج كله يترك variantId فارغاً، وMySQL — كـPostgreSQL — يعتبر
-- NULL مميّزاً عن NULL. فصفّان متطابقان تماماً بفراغين يمرّان من القيد
-- الفريد، ويصير للكمية الواحدة سعران، ويُعرض أيّهما يعود أولاً من الفهرس.
-- سعر يظهر بالحظّ، على وثيقة تذهب إلى العميل.
--
-- عولجت في PostgreSQL بـ NULLS NOT DISTINCT، ولا مقابل لها هنا. البديل
-- عمود مولَّد يطوي الفراغ إلى نصّ فارغ ويدخل الفهرس مكان العمود الأصلي.
-- لا يُكتب إليه ولا يُقرأ منه في التطبيق — يوجد ليمنع فقط.
--
-- ── لماذا VIRTUAL لا STORED ────────────────────────────────
--
-- المخزَّن هو الأولى عادةً لأن الفهرس عليه أرخص. لكن MariaDB ترفضه هنا:
-- variantId طرف في مفتاح أجنبي بـ ON UPDATE CASCADE، وقيمة مخزَّنة مشتقّة
-- من عمود قد تغيّره القاعدة تحتها ممنوعة صراحةً (خطأ 1901). الافتراضي
-- يُحسب عند القراءة فلا يقع في ذلك، ويقبله الفهرس الفريد في MariaDB 10.2+
-- وMySQL 5.7+ معاً — وأيّهما تقدّمه الاستضافة يعمل.
--
-- ── الترتيب ────────────────────────────────────────────────
--
-- الفهرس الجديد يُنشأ قبل حذف القديم، فلا تمرّ لحظة يكون الجدول فيها بلا
-- حارس. وإنشاؤه يفشل إن كان في الجدول تكرارٌ سابق — وهو السلوك المطلوب:
-- بيانات مكسورة تُرى ولا تُلفّ حولها.

ALTER TABLE `PriceTier`
  ADD COLUMN `variantKey` VARCHAR(191)
    GENERATED ALWAYS AS (IFNULL(`variantId`, '')) VIRTUAL;

CREATE UNIQUE INDEX `PriceTier_productId_variantKey_service_minQty_key`
  ON `PriceTier` (`productId`, `variantKey`, `service`, `minQty`);

DROP INDEX `PriceTier_productId_variantId_service_minQty_key` ON `PriceTier`;

-- الفهرس المحذوف كان يخدم البحث بالمتغيّر أيضاً، وعليه مفتاح أجنبي
-- يحتاج فهرساً. يُعاد كفهرس عادي.
CREATE INDEX `PriceTier_variantId_idx` ON `PriceTier` (`variantId`);
